-- Events Manager tables for the Unified Pentagonal Project
-- (`src/modules/events.rs`): events with venues and recurring
-- series, materialised occurrences, ticket types, registrations,
-- attendees, waitlist entries, and reminders.
-- Matches src/db/schema.rs conventions. PostgreSQL only.
-- Run with diesel_migrations (embedded via src/db/mod.rs).
--
-- THIS MIGRATION HAS NEVER BEEN EXECUTED AGAINST A LIVE
-- POSTGRESQL DATABASE. It is a persistence target for the
-- in-memory DashMap stores in `src/modules/events.rs`, which stay
-- authoritative until the migration is executed and verified.
--
-- Notes on the mapping (the in-memory DashMap store is still
-- authoritative; see TODO.md):
--   - `events.organizer_id` and `event_registrations.user_id`
--     (and `event_attendees` names/emails) are plain VARCHAR user
--     ids: the module identifies callers by the `X-User-Id` header
--     and keeps user ids as strings, exactly like
--     `store_orders.user_id` in migration 000002. No foreign key
--     to `users` is stored here. `events.company_id` is likewise a
--     plain VARCHAR reference to the company module.
--   - `events.status` is `draft`, `published`, `ongoing`,
--     `completed`, or `cancelled` (`EventStatus`); `visibility` is
--     `public`, `draft`, or `private` (`EventVisibility`). The
--     module derives `ongoing` / `completed` at read time from the
--     event window; the stored status never moves to `ongoing` on
--     its own.
--   - `events.slug` is unique (lowercase letters, digits, single
--     hyphens; validated in the module). `cover_storage_target` /
--     `cover_storage_key` are metadata only: the cover image bytes
--     live in the storage module, referenced by target + key.
--   - `events.recurrence` is JSONB holding the `RecurrenceRule`
--     (`frequency` daily/weekly/monthly/yearly, `interval`,
--     optional `count` / `until`, `exceptions` as occurrence start
--     times to skip). `count` and `until` are mutually exclusive
--     in the module (`count` wins); the CHECK below only bounds
--     `count` to 1..366, matching `MAX_OCCURRENCES`.
--   - `event_occurrences` are the materialised rows for a series
--     (one row per occurrence, up to 366; a one-off event has one
--     row). `status` is `scheduled`, `cancelled`, or `completed`;
--     `overridden` marks a row whose time/venue differs from the
--     series default or that was cancelled on its own.
--   - `event_ticket_types.price` is NUMERIC(19,4) (money), never
--     negative; `quantity` and `sold` are never negative and
--     `sold` never exceeds `quantity` at write time in the module
--     (the CHECK below enforces `sold <= quantity` as a second
--     line of defence). `per_order_limit` is 1..100.
--   - `event_registrations.status` is `pending_payment`,
--     `pending_verification`, `confirmed`, `waitlisted`, or
--     `cancelled` (`RegistrationStatus`). `total_amount` is
--     NUMERIC(19,4). `order_id` is the store/billing order id
--     when the registration was paid through the store (plain
--     VARCHAR reference, no FK: the store owns orders).
--     `check_in_code` is the code the attendee presents at the
--     door (the code value only — no QR image is generated by
--     this module). `refund_reason` records a requested refund;
--     refunds themselves are NOT processed here (the billing /
--     store side owns them, via
--     `events.registration.refund_requested`).
--   - `event_attendees.custom_answers` is JSONB holding the
--     answers to the event's custom registration questions.
--   - `event_waitlist.position` is 1-based in arrival order;
--     promotion takes the lowest position first.
--   - `event_reminders.offset_minutes` is how long before the
--     event start the reminder fires (1440 = 24h, 60 = 1h by
--     default). `scheduler_status` is `not_scheduled`, `queued`,
--     or `declined`: the scheduler does not know the
--     `events.reminders.send` job kind yet, so reminders record
--     `declined` until that kind is added to `KNOWN_KINDS` in
--     `scheduler.rs`.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ---------------------------------------------------------------------------
-- One event.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    slug VARCHAR(128) NOT NULL,
    category TEXT[] NOT NULL DEFAULT '{}',
    tags TEXT[] NOT NULL DEFAULT '{}',
    venue_name VARCHAR(200),
    venue_address VARCHAR(500),
    venue_latitude DOUBLE PRECISION CHECK (venue_latitude IS NULL OR (venue_latitude >= -90 AND venue_latitude <= 90)),
    venue_longitude DOUBLE PRECISION CHECK (venue_longitude IS NULL OR (venue_longitude >= -180 AND venue_longitude <= 180)),
    venue_capacity BIGINT CHECK (venue_capacity IS NULL OR venue_capacity >= 0),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
    visibility VARCHAR NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'draft', 'private')),
    status VARCHAR NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'ongoing', 'completed', 'cancelled')),
    organizer_id VARCHAR NOT NULL,
    company_id VARCHAR,
    cover_storage_target VARCHAR(512),
    cover_storage_key VARCHAR(512),
    recurrence JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at),
    CHECK ((cover_storage_target IS NULL) = (cover_storage_key IS NULL)),
    CHECK (recurrence IS NULL OR (recurrence ->> 'count') IS NULL OR ((recurrence ->> 'count')::INTEGER BETWEEN 1 AND 366))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_events_slug ON events (slug);
CREATE INDEX IF NOT EXISTS idx_events_organizer_id ON events (organizer_id);
CREATE INDEX IF NOT EXISTS idx_events_status ON events (status);
CREATE INDEX IF NOT EXISTS idx_events_visibility ON events (visibility);
CREATE INDEX IF NOT EXISTS idx_events_starts_at ON events (starts_at);
CREATE INDEX IF NOT EXISTS idx_events_ends_at ON events (ends_at);

-- ---------------------------------------------------------------------------
-- One materialised occurrence of an event.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_occurrences (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    sequence INTEGER NOT NULL CHECK (sequence >= 1),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'cancelled', 'completed')),
    venue_name VARCHAR(200),
    venue_address VARCHAR(500),
    venue_latitude DOUBLE PRECISION CHECK (venue_latitude IS NULL OR (venue_latitude >= -90 AND venue_latitude <= 90)),
    venue_longitude DOUBLE PRECISION CHECK (venue_longitude IS NULL OR (venue_longitude >= -180 AND venue_longitude <= 180)),
    venue_capacity BIGINT CHECK (venue_capacity IS NULL OR venue_capacity >= 0),
    overridden BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_event_occurrences_event_sequence
    ON event_occurrences (event_id, sequence);
CREATE INDEX IF NOT EXISTS idx_event_occurrences_event_id ON event_occurrences (event_id);
CREATE INDEX IF NOT EXISTS idx_event_occurrences_starts_at ON event_occurrences (starts_at);
CREATE INDEX IF NOT EXISTS idx_event_occurrences_status ON event_occurrences (status);

-- ---------------------------------------------------------------------------
-- One ticket type of an event.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_ticket_types (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    price NUMERIC(19, 4) NOT NULL DEFAULT 0 CHECK (price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    quantity BIGINT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    sold BIGINT NOT NULL DEFAULT 0 CHECK (sold >= 0),
    sales_start TIMESTAMPTZ,
    sales_end TIMESTAMPTZ,
    per_order_limit BIGINT NOT NULL DEFAULT 10 CHECK (per_order_limit >= 1 AND per_order_limit <= 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (sold <= quantity),
    CHECK (sales_end IS NULL OR sales_start IS NULL OR sales_end > sales_start)
);

CREATE INDEX IF NOT EXISTS idx_event_ticket_types_event_id ON event_ticket_types (event_id);

-- ---------------------------------------------------------------------------
-- One registration: one user, one event, one ticket type.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_registrations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    occurrence_id UUID REFERENCES event_occurrences (id) ON DELETE SET NULL,
    ticket_type_id UUID NOT NULL REFERENCES event_ticket_types (id) ON DELETE RESTRICT,
    user_id VARCHAR NOT NULL,
    quantity BIGINT NOT NULL DEFAULT 1 CHECK (quantity >= 1),
    total_amount NUMERIC(19, 4) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    status VARCHAR NOT NULL DEFAULT 'pending_payment'
        CHECK (status IN ('pending_payment', 'pending_verification', 'confirmed', 'waitlisted', 'cancelled')),
    order_id VARCHAR,
    payment_reference VARCHAR,
    payment_provider VARCHAR,
    check_in_code VARCHAR(64) NOT NULL,
    checked_in_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    refund_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_event_registrations_check_in_code
    ON event_registrations (check_in_code);
CREATE INDEX IF NOT EXISTS idx_event_registrations_event_id ON event_registrations (event_id);
CREATE INDEX IF NOT EXISTS idx_event_registrations_user_id ON event_registrations (user_id);
CREATE INDEX IF NOT EXISTS idx_event_registrations_status ON event_registrations (status);
CREATE INDEX IF NOT EXISTS idx_event_registrations_ticket_type_id ON event_registrations (ticket_type_id);
CREATE INDEX IF NOT EXISTS idx_event_registrations_order_id ON event_registrations (order_id);

-- ---------------------------------------------------------------------------
-- One attendee: one seat behind a registration.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_attendees (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    registration_id UUID NOT NULL REFERENCES event_registrations (id) ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(254) NOT NULL,
    custom_answers JSONB NOT NULL DEFAULT '{}'::JSONB,
    checked_in_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_event_attendees_event_id ON event_attendees (event_id);
CREATE INDEX IF NOT EXISTS idx_event_attendees_registration_id ON event_attendees (registration_id);
CREATE INDEX IF NOT EXISTS idx_event_attendees_email ON event_attendees (email);
CREATE INDEX IF NOT EXISTS idx_event_attendees_checked_in_at ON event_attendees (checked_in_at);

-- ---------------------------------------------------------------------------
-- One waitlist entry.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_waitlist (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    ticket_type_id UUID NOT NULL REFERENCES event_ticket_types (id) ON DELETE CASCADE,
    user_id VARCHAR NOT NULL,
    quantity BIGINT NOT NULL DEFAULT 1 CHECK (quantity >= 1),
    position BIGINT NOT NULL CHECK (position >= 1),
    status VARCHAR NOT NULL DEFAULT 'waiting'
        CHECK (status IN ('waiting', 'promoted', 'expired', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_event_waitlist_event_id ON event_waitlist (event_id);
CREATE INDEX IF NOT EXISTS idx_event_waitlist_ticket_type_id ON event_waitlist (ticket_type_id);
CREATE INDEX IF NOT EXISTS idx_event_waitlist_status ON event_waitlist (status);
CREATE INDEX IF NOT EXISTS idx_event_waitlist_position ON event_waitlist (event_id, ticket_type_id, position);

-- ---------------------------------------------------------------------------
-- One reminder for an event.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event_reminders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id UUID NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    offset_minutes BIGINT NOT NULL CHECK (offset_minutes >= 0 AND offset_minutes <= 525600),
    occurrence_id UUID REFERENCES event_occurrences (id) ON DELETE SET NULL,
    title_template VARCHAR(500),
    body_template TEXT,
    status VARCHAR NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sent', 'failed', 'cancelled')),
    scheduler_job_id VARCHAR,
    scheduler_status VARCHAR NOT NULL DEFAULT 'not_scheduled'
        CHECK (scheduler_status IN ('not_scheduled', 'queued', 'declined')),
    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_event_reminders_event_id ON event_reminders (event_id);
CREATE INDEX IF NOT EXISTS idx_event_reminders_status ON event_reminders (status);
