-- Logistics module tables for the Unified Pentagonal Project
-- (`src/modules/logistics.rs`): shipments with a status timeline,
-- fleet vehicles with maintenance reminders, drivers, warehouses,
-- stock movements, delivery routes with ordered stops, proofs of
-- delivery, delivery exceptions, and shipping rate tables.
-- Matches src/db/schema.rs conventions. PostgreSQL only.
-- Run with diesel_migrations (embedded via src/db/mod.rs).
--
-- THIS MIGRATION HAS NEVER BEEN EXECUTED AGAINST A LIVE
-- POSTGRESQL DATABASE. It is a persistence target for the
-- in-memory DashMap stores in `src/modules/logistics.rs`, which stay
-- authoritative until the migration is executed and verified.
--
-- Notes on the mapping (the in-memory DashMap store is still
-- authoritative; see TODO.md):
--   - `logistics_shipments.order_id` is a plain VARCHAR reference
--     to the store module's order id (a string id, exactly like
--     `store_orders.id`): no foreign key, because the store owns
--     orders and this module never duplicates order rows.
--     `order_link_status` is `linked` (the store confirmed the
--     order through `store.order.lookup`), `unverified` (no store
--     answer yet), or `none`.
--   - `logistics_shipments.tracking_number` is unique
--     (`LG-<8 digits>-<Luhn check digit>`, generated by the
--     module). `tracking_token_hash` is the SHA-256 hex of the
--     public tracking verification token; the raw token is shown
--     once at creation and never stored.
--   - `logistics_shipments.status` is `created`, `picked_up`,
--     `in_transit`, `out_for_delivery`, `delivered`, `exception`,
--     `returned`, or `cancelled` (`ShipmentStatus`). The module
--     enforces the transition table in code; the CHECK below is a
--     second line of defence only.
--   - `user_id` columns are TEXT with NO foreign key on purpose:
--     actor ids in this codebase are opaque strings (the
--     `X-User-Id` header), not necessarily the UUID primary key of
--     the `users` table. `logistics_drivers.user_id` references a
--     user by id and never duplicates user rows; `created_by` and
--     `actor` columns are the same kind of reference.
--   - `company_id` columns DO reference `companies (id)` (created
--     by migration 000001), ON DELETE CASCADE: deleting a company
--     removes its shipments, vehicles, warehouses, routes, and
--     rate tables. Driver rows have no company column (a driver
--     is a person record, not a company asset).
--   - Money is NUMERIC(19,4): `logistics_shipments.shipping_cost`
--     and `logistics_rate_tables.base_price` / `per_kg` /
--     `per_km`. Weights and dimensions are DOUBLE PRECISION
--     (physical measurements, not money).
--   - `logistics_proofs` stores metadata ONLY: `storage_target`
--     and `storage_key` identify the photo in the storage module,
--     `signature_storage_target` / `signature_storage_key` the
--     signature image, and `content_sha256` is the SHA-256 hex of
--     the uploaded bytes. No photo or signature bytes live in this
--     schema.
--   - `logistics_stock_movements` records quantities only: the
--     assets / inventory module owns the item master data, so
--     `asset_id` is the assets stock item id (plain UUID, no
--     foreign key) and no item name or price is stored here.
--     `quantity_after` is the on-hand count for the
--     (warehouse, asset) pair right after the move; `out` moves
--     may never take the balance below zero (enforced in the
--     module).
--   - `logistics_vehicles.maintenance` is JSONB holding the
--     maintenance reminders (`id`, `description`, `due_date`,
--     `status` pending/due/done, `scheduler_job_id`,
--     `scheduler_status` not_scheduled/queued/declined,
--     `completed_at`). `scheduler_status` is `declined` until the
--     `logistics.maintenance.remind` job kind is added to the
--     scheduler's `KNOWN_KINDS` list.
--   - `logistics_routes` carry an optional start point; route
--     optimisation is out of scope, so no optimiser state is
--     stored. `logistics_route_stops.sequence` is 1-based and
--     contiguous per route (the module renumbers after deletes
--     and reorders).
--   - `logistics_exceptions.status` is `open`, `investigating`,
--     `resolved`, or `returned`; `previous_status` is the
--     shipment status before the exception, so a resolution can
--     restore it.
--   - `logistics_rate_tables` with both zones NULL is the
--     wildcard (fallback) table. Cost is `base_price` +
--     `per_kg` * billable weight + `per_km` * distance; billable
--     weight is max(actual weight, dimensional weight with the
--     5000 divisor), computed by the module at quote time.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";



-- ---------------------------------------------------------------------------
-- Drivers (user references only; the users module owns user rows).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_drivers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT NOT NULL UNIQUE,
    license_number VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    status VARCHAR NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive', 'on_leave')),
    current_vehicle_id UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_drivers_user ON logistics_drivers (user_id);
CREATE INDEX IF NOT EXISTS idx_logistics_drivers_status ON logistics_drivers (status);

-- ---------------------------------------------------------------------------
-- Fleet vehicles.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_vehicles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    plate VARCHAR(20) NOT NULL UNIQUE,
    vehicle_type VARCHAR NOT NULL
        CHECK (vehicle_type IN ('van', 'truck', 'motorcycle', 'car', 'other')),
    capacity_kg DOUBLE PRECISION NOT NULL CHECK (capacity_kg > 0 AND capacity_kg <= 100000),
    status VARCHAR NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'in_service', 'maintenance', 'retired')),
    assigned_driver_id UUID REFERENCES logistics_drivers (id) ON DELETE SET NULL,
    company_id UUID REFERENCES companies (id) ON DELETE CASCADE,
    maintenance JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_vehicles_status ON logistics_vehicles (status);
CREATE INDEX IF NOT EXISTS idx_logistics_vehicles_company ON logistics_vehicles (company_id);
CREATE INDEX IF NOT EXISTS idx_logistics_vehicles_driver ON logistics_vehicles (assigned_driver_id);

-- Drivers reference vehicles too (circular with the assignment
-- above), so the foreign key is added after both tables exist.
ALTER TABLE logistics_drivers
    ADD CONSTRAINT fk_logistics_drivers_current_vehicle
    FOREIGN KEY (current_vehicle_id) REFERENCES logistics_vehicles (id) ON DELETE SET NULL;

-- ---------------------------------------------------------------------------
-- Warehouses.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_warehouses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(200) NOT NULL,
    address VARCHAR(500) NOT NULL,
    capacity BIGINT NOT NULL CHECK (capacity >= 0),
    manager_user_id TEXT,
    default_low_stock_threshold BIGINT NOT NULL DEFAULT 0 CHECK (default_low_stock_threshold >= 0),
    company_id UUID REFERENCES companies (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_warehouses_company ON logistics_warehouses (company_id);

-- ---------------------------------------------------------------------------
-- One shipment.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_shipments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tracking_number VARCHAR(20) NOT NULL UNIQUE,
    tracking_token_hash VARCHAR(64) NOT NULL,
    order_id VARCHAR,
    order_link_status VARCHAR NOT NULL DEFAULT 'none'
        CHECK (order_link_status IN ('linked', 'unverified', 'none')),
    company_id UUID REFERENCES companies (id) ON DELETE CASCADE,
    status VARCHAR NOT NULL DEFAULT 'created'
        CHECK (status IN ('created', 'picked_up', 'in_transit', 'out_for_delivery', 'delivered', 'exception', 'returned', 'cancelled')),
    origin_address VARCHAR(500) NOT NULL,
    origin_latitude DOUBLE PRECISION CHECK (origin_latitude IS NULL OR (origin_latitude >= -90 AND origin_latitude <= 90)),
    origin_longitude DOUBLE PRECISION CHECK (origin_longitude IS NULL OR (origin_longitude >= -180 AND origin_longitude <= 180)),
    destination_address VARCHAR(500) NOT NULL,
    destination_latitude DOUBLE PRECISION CHECK (destination_latitude IS NULL OR (destination_latitude >= -90 AND destination_latitude <= 90)),
    destination_longitude DOUBLE PRECISION CHECK (destination_longitude IS NULL OR (destination_longitude >= -180 AND destination_longitude <= 180)),
    weight_kg DOUBLE PRECISION NOT NULL CHECK (weight_kg > 0 AND weight_kg <= 100000),
    length_cm DOUBLE PRECISION NOT NULL CHECK (length_cm > 0 AND length_cm <= 10000),
    width_cm DOUBLE PRECISION NOT NULL CHECK (width_cm > 0 AND width_cm <= 10000),
    height_cm DOUBLE PRECISION NOT NULL CHECK (height_cm > 0 AND height_cm <= 10000),
    zone_origin VARCHAR(64) NOT NULL,
    zone_destination VARCHAR(64) NOT NULL,
    service_level VARCHAR(64) NOT NULL DEFAULT 'standard',
    driver_id UUID REFERENCES logistics_drivers (id) ON DELETE SET NULL,
    vehicle_id UUID REFERENCES logistics_vehicles (id) ON DELETE SET NULL,
    warehouse_id UUID REFERENCES logistics_warehouses (id) ON DELETE SET NULL,
    scheduled_at TIMESTAMPTZ,
    window_start TIMESTAMPTZ,
    window_end TIMESTAMPTZ,
    estimated_delivery_at TIMESTAMPTZ,
    shipping_cost NUMERIC(19, 4) CHECK (shipping_cost IS NULL OR shipping_cost >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (window_end IS NULL OR window_start IS NULL OR window_end > window_start)
);

CREATE INDEX IF NOT EXISTS idx_logistics_shipments_tracking ON logistics_shipments (tracking_number);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_status ON logistics_shipments (status);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_order ON logistics_shipments (order_id);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_company ON logistics_shipments (company_id);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_driver ON logistics_shipments (driver_id);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_vehicle ON logistics_shipments (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_logistics_shipments_warehouse ON logistics_shipments (warehouse_id);

-- ---------------------------------------------------------------------------
-- Shipment timeline: every transition with actor, location, note.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_shipment_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shipment_id UUID NOT NULL REFERENCES logistics_shipments (id) ON DELETE CASCADE,
    kind VARCHAR NOT NULL DEFAULT 'status_change'
        CHECK (kind IN ('status_change', 'rescheduled', 'note', 'exception_opened', 'exception_resolved', 'proof_recorded', 'order_linked')),
    from_status VARCHAR
        CHECK (from_status IS NULL OR from_status IN ('created', 'picked_up', 'in_transit', 'out_for_delivery', 'delivered', 'exception', 'returned', 'cancelled')),
    to_status VARCHAR
        CHECK (to_status IS NULL OR to_status IN ('created', 'picked_up', 'in_transit', 'out_for_delivery', 'delivered', 'exception', 'returned', 'cancelled')),
    actor TEXT NOT NULL,
    location VARCHAR(500),
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_shipment_events_shipment ON logistics_shipment_events (shipment_id);
CREATE INDEX IF NOT EXISTS idx_logistics_shipment_events_created ON logistics_shipment_events (created_at);







-- ---------------------------------------------------------------------------
-- Stock movements (quantities only; assets own the item master data).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_stock_movements (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    warehouse_id UUID NOT NULL REFERENCES logistics_warehouses (id) ON DELETE CASCADE,
    asset_id UUID NOT NULL,
    direction VARCHAR NOT NULL CHECK (direction IN ('in', 'out')),
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    quantity_after BIGINT NOT NULL CHECK (quantity_after >= 0),
    reason VARCHAR(500) NOT NULL,
    shipment_id UUID REFERENCES logistics_shipments (id) ON DELETE SET NULL,
    actor TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_stock_movements_warehouse ON logistics_stock_movements (warehouse_id);
CREATE INDEX IF NOT EXISTS idx_logistics_stock_movements_asset ON logistics_stock_movements (asset_id);
CREATE INDEX IF NOT EXISTS idx_logistics_stock_movements_shipment ON logistics_stock_movements (shipment_id);

-- ---------------------------------------------------------------------------
-- Delivery routes.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_routes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(200) NOT NULL,
    driver_id UUID REFERENCES logistics_drivers (id) ON DELETE SET NULL,
    vehicle_id UUID REFERENCES logistics_vehicles (id) ON DELETE SET NULL,
    route_date TIMESTAMPTZ NOT NULL,
    start_latitude DOUBLE PRECISION CHECK (start_latitude IS NULL OR (start_latitude >= -90 AND start_latitude <= 90)),
    start_longitude DOUBLE PRECISION CHECK (start_longitude IS NULL OR (start_longitude >= -180 AND start_longitude <= 180)),
    status VARCHAR NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned', 'active', 'completed', 'cancelled')),
    company_id UUID REFERENCES companies (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_routes_status ON logistics_routes (status);
CREATE INDEX IF NOT EXISTS idx_logistics_routes_company ON logistics_routes (company_id);
CREATE INDEX IF NOT EXISTS idx_logistics_routes_driver ON logistics_routes (driver_id);

-- ---------------------------------------------------------------------------
-- Ordered stops on a delivery route.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_route_stops (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    route_id UUID NOT NULL REFERENCES logistics_routes (id) ON DELETE CASCADE,
    shipment_id UUID REFERENCES logistics_shipments (id) ON DELETE SET NULL,
    sequence BIGINT NOT NULL CHECK (sequence >= 1),
    address VARCHAR(500) NOT NULL,
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90)),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
    status VARCHAR NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'visited', 'skipped')),
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (route_id, sequence)
);

CREATE INDEX IF NOT EXISTS idx_logistics_route_stops_route ON logistics_route_stops (route_id);
CREATE INDEX IF NOT EXISTS idx_logistics_route_stops_shipment ON logistics_route_stops (shipment_id);

-- ---------------------------------------------------------------------------
-- Proof of delivery (storage references + hash only).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_proofs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shipment_id UUID NOT NULL REFERENCES logistics_shipments (id) ON DELETE CASCADE,
    storage_target VARCHAR(200) NOT NULL,
    storage_key VARCHAR(1024) NOT NULL,
    content_sha256 VARCHAR(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    signature_storage_target VARCHAR(200),
    signature_storage_key VARCHAR(1024),
    recipient_name VARCHAR(200) NOT NULL,
    delivered_at TIMESTAMPTZ NOT NULL,
    actor TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_proofs_shipment ON logistics_proofs (shipment_id);

-- ---------------------------------------------------------------------------
-- Delivery exceptions.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_exceptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shipment_id UUID NOT NULL REFERENCES logistics_shipments (id) ON DELETE CASCADE,
    exception_type VARCHAR NOT NULL
        CHECK (exception_type IN ('damaged', 'refused', 'address_issue', 'weather', 'lost', 'other')),
    description TEXT NOT NULL,
    status VARCHAR NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'investigating', 'resolved', 'returned')),
    previous_status VARCHAR NOT NULL
        CHECK (previous_status IN ('created', 'picked_up', 'in_transit', 'out_for_delivery', 'delivered', 'exception', 'returned', 'cancelled')),
    resolution TEXT,
    actor TEXT NOT NULL,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_exceptions_shipment ON logistics_exceptions (shipment_id);
CREATE INDEX IF NOT EXISTS idx_logistics_exceptions_status ON logistics_exceptions (status);

-- ---------------------------------------------------------------------------
-- Shipping rate tables.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS logistics_rate_tables (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(200) NOT NULL,
    origin_zone VARCHAR(64),
    destination_zone VARCHAR(64),
    base_price NUMERIC(19, 4) NOT NULL CHECK (base_price >= 0),
    per_kg NUMERIC(19, 4) NOT NULL CHECK (per_kg >= 0),
    per_km NUMERIC(19, 4) NOT NULL CHECK (per_km >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    company_id UUID REFERENCES companies (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logistics_rate_tables_zones ON logistics_rate_tables (origin_zone, destination_zone);
CREATE INDEX IF NOT EXISTS idx_logistics_rate_tables_company ON logistics_rate_tables (company_id);
