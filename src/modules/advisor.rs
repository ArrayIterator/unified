// Advisor module.
//
// A rule-based recommendations engine over company data. Every
// suggestion names the rule that produced it, the severity formula
// that graded it, and the exact source records and figures behind
// it. There is no scoring model, no machine learning, and no
// black-box number anywhere in this module: a suggestion is only
// ever the transparent output of one named rule evaluated against
// facts the module observed or was given.
//
// Rules (see `RULE_DEFINITIONS` and `GET /api/v1/advisor/rules`
// for the same text at runtime):
//
//   1. `cashflow.overdue_invoices` — aggregate cash-flow warning
//      from billing invoices. Condition: at least one invoice for
//      the company is overdue (past due date with a balance
//      outstanding). Severity formula: critical when the overdue
//      balance is >= 5000 (currency units) or at least 10 invoices
//      are overdue; warning otherwise.
//   2. `cashflow.falling_collections` — collections trend from
//      recorded payments. Condition: payments recorded in the last
//      30 days total less than payments in the 30 days before that.
//      Severity formula: drop_pct = (previous - current) / previous
//      * 100; critical when drop_pct >= 50, warning when
//      drop_pct >= 25. Fires only when the previous window total is
//      greater than zero, so a company with no payment history never
//      gets a trend suggestion from an empty baseline.
//   3. `billing.overdue_invoice_followup` — one suggestion per
//      overdue invoice. Condition: an invoice is overdue.
//      Severity formula, from days overdue: 1-7 days is info, 8-30
//      days is warning, more than 30 days is critical.
//   4. `crm.churn_inactive_client` — churn signal from CRM
//      activity. Condition: a contact has had no recorded activity
//      for at least 90 days. Severity formula: 90-179 days without
//      activity is warning, 180 days or more is critical.
//   5. `licensing.expiring_license` — expiring licenses from the
//      licensing module. Condition: a `license.expiring` event
//      arrived. Severity formula, from days remaining: expired or
//      7 days or fewer is critical, 8-30 days is warning, 31-60
//      days is info.
//   6. `billing.underused_subscription` — paid but unused seats.
//      Condition: a subscription snapshot reports seats used below
//      half of the seats purchased. Severity formula, from
//      utilisation = seats_used / seats_purchased * 100: 10% or
//      below is critical, above 10% and below 50% is warning.
//
// Suggestions are generated by evaluating rules on demand
// (`POST /api/v1/advisor/suggestions/re-evaluate` and the
// `advisor.evaluate_requested` hook) and are never auto-acted on:
// acknowledging, dismissing, or snoozing a suggestion only changes
// its status. Re-evaluation refreshes the figures of open
// suggestions instead of creating duplicates (see `dedupe_key`).
//
// Data sources, verified against the source modules:
//   - Billing emits full invoice JSON on `invoice.created`,
//     `invoice.paid`, `invoice.payment.recorded`, and
//     `invoice.voided` (Invoice carries `company_id`, `total`,
//     `balance`, `status`, `overdue`, `due_date`, `amount_paid`).
//     The advisor caches those facts locally; it never queries the
//     billing database directly.
//   - Licensing emits `license.expiring` with `license_id`,
//     `license_key`, `days_remaining`, `threshold_days`, `expired`,
//     and `expires_at`.
//   - CRM emits no contact-activity event (its only emits are
//     `company.create_requested` and `user.create_requested`), and
//     its Contact record carries no last-activity field, so rule 4
//     can only evaluate activity snapshots supplied with the
//     re-evaluate request (`crm_activities` in the payload). The
//     gap is recorded in the rule definition and in the evaluation
//     result; the rule never invents activity data.
//   - The store emits order events only and carries no seat-usage
//     data, so rule 6 can only evaluate subscription snapshots
//     supplied with the re-evaluate request (`subscriptions` in the
//     payload). Same honest-gap handling as rule 4.
//   - No source module answers a `*_requested` data query for
//     invoices, licenses, contacts, or subscriptions, so there is
//     no pull path: evaluation works from observed events plus
//     request payloads only.
//
// Events emitted by this module:
//   - `advisor.suggestion_created` — a new suggestion was stored.
//   - `advisor.suggestion_acknowledged` — a suggestion was
//     acknowledged by a human.
//   - `advisor.suggestion_dismissed`, `advisor.suggestion_snoozed`
//     — status changes (extra lifecycle events; the audit module
//     records any of these once the integrator adds them to its
//     audited list, see INTEGRATION_NOTES_BATCH3_B4.md).
//   - `notification.requested` — critical suggestions only, sent
//     to the user the source record belongs to when one is known,
//     otherwise to `system` (the same fallback the licensing
//     module uses for its expiry alerts).
//   - `advisor.evaluate_requested` is answered, not emitted: any
//     caller (scheduler job, admin tooling) may emit it with a
//     `company_id` to trigger evaluation.
//
// Interconnection happens only through the hook bus — no module
// calls another module directly. Money is NUMERIC(19,4) in SQL
// (see the migration); the in-memory store keeps amounts as f64,
// matching the billing module's Invoice shape.

