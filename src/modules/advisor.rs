/// Cache the invoice carried by `invoice.created`, `invoice.paid`,
/// or `invoice.voided` (all three emit the full invoice JSON).
fn on_invoice_event(state: Arc<AdvisorState>, ctx: &mut HookContext) {
    let data = ctx.data.clone();
    let Some(id) = data.get("id").and_then(|v| v.as_str()) else {
        return;
    };
    let fact = InvoiceFact {
        id: id.to_string(),
        company_id: data
            .get("company_id")
            .and_then(|v| v.as_str())
            .map(str::to_string),
        user_id: data
            .get("user_id")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string(),
        number: data
            .get("number")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string(),
        total: data.get("total").and_then(|v| v.as_f64()).unwrap_or(0.0),
        balance: data.get("balance").and_then(|v| v.as_f64()).unwrap_or(0.0),
        currency: data
            .get("currency")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string(),
        status: data
            .get("status")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string(),
        overdue: data
            .get("overdue")
            .and_then(|v| v.as_bool())
            .unwrap_or(false),
        due_date: data
            .get("due_date")
            .and_then(|v| v.as_str())
            .and_then(|value| value.parse::<DateTime<Utc>>().ok()),
        updated_at: Utc::now(),
    };
    state.invoices.insert(fact.id.clone(), fact);
}

/// Cache one payment from `invoice.payment.recorded` and refresh
/// the invoice balance when the payload carries it. The company is
/// resolved through the cached invoice when the payload does not
/// name one, so collections stay attributed to the right company.
fn on_payment_recorded(state: Arc<AdvisorState>, ctx: &mut HookContext) {
    let data = ctx.data.clone();
    let amount = data.get("amount").and_then(|v| v.as_f64()).unwrap_or(0.0);
    if amount <= 0.0 {
        return;
    }
    let invoice_id = data
        .get("invoice_id")
        .and_then(|v| v.as_str())
        .map(str::to_string);
    let mut company_id = data
        .get("company_id")
        .and_then(|v| v.as_str())
        .map(str::to_string);
    if company_id.is_none() {
        if let Some(invoice_id) = &invoice_id {
            company_id = state
                .invoices
                .get(invoice_id)
                .and_then(|invoice| invoice.company_id.clone());
        }
    }
    let paid_at = data
        .get("paid_at")
        .or_else(|| data.get("created_at"))
        .and_then(|v| v.as_str())
        .and_then(|value| value.parse::<DateTime<Utc>>().ok())
        .unwrap_or_else(Utc::now);
    let id = data
        .get("id")
        .and_then(|v| v.as_str())
        .map(str::to_string)
        .unwrap_or_else(new_id);
    state.payments.insert(
        id.clone(),
        PaymentFact {
            id,
            company_id,
            invoice_id: invoice_id.clone(),
            amount,
            paid_at,
        },
    );
    if let Some(invoice_id) = invoice_id {
        if let Some(mut invoice) = state.invoices.get_mut(&invoice_id) {
            if let Some(balance) = data.get("balance").and_then(|v| v.as_f64()) {
                invoice.balance = balance;
            }
            if let Some(status) = data.get("status").and_then(|v| v.as_str()) {
                invoice.status = status.to_string();
            }
            invoice.updated_at = Utc::now();
        }
    }
}

/// Cache the license expiry fact from `license.expiring` and
/// evaluate the expiring-license rule immediately, so the
/// suggestion exists without waiting for the next scheduled run.
fn on_license_expiring(state: Arc<AdvisorState>, ctx: &mut HookContext) {
    let data = ctx.data.clone();
    let Some(license_id) = data.get("license_id").and_then(|v| v.as_str()) else {
        return;
    };
    let fact = LicenseFact {
        license_id: license_id.to_string(),
        license_key: data
            .get("license_key")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string(),
        days_remaining: data
            .get("days_remaining")
            .and_then(|v| v.as_i64())
            .unwrap_or(0),
        expired: data
            .get("expired")
            .and_then(|v| v.as_bool())
            .unwrap_or(false),
        expires_at: data
            .get("expires_at")
            .and_then(|v| v.as_str())
            .and_then(|value| value.parse::<DateTime<Utc>>().ok()),
        seen_at: Utc::now(),
    };
    state.licenses.insert(fact.license_id.clone(), fact);
    state.evaluate(None, &["licensing.expiring_license".to_string()]);
}

/// Answer `advisor.evaluate_requested` by running the evaluation
/// for the requested company (or all companies) and reporting the
/// outcome as the hook result. Snapshots in the payload
/// (`crm_activities`, `subscriptions`) are stored first, so the
/// churn and underused-subscription rules can use them.
fn on_evaluate_requested(state: Arc<AdvisorState>, ctx: &mut HookContext) {
    let data = ctx.data.clone();
    let company_id = data
        .get("company_id")
        .and_then(|v| v.as_str())
        .map(str::to_string)
        .filter(|value| !value.is_empty());
    if let Some(activities) = data.get("crm_activities").and_then(|v| v.as_array()) {
        for raw in activities {
            if let Ok(activity) = serde_json::from_value::<CrmActivitySnapshot>(raw.clone()) {
                if !activity.contact_id.trim().is_empty() {
                    state
                        .crm_activities
                        .insert(activity.contact_id.clone(), activity);
                }
            }
        }
    }
    if let Some(subscriptions) = data.get("subscriptions").and_then(|v| v.as_array()) {
        for raw in subscriptions {
            if let Ok(subscription) = serde_json::from_value::<SubscriptionSnapshot>(raw.clone()) {
                if !subscription.subscription_id.trim().is_empty()
                    && subscription.seats_used <= subscription.seats_purchased
                    && subscription.amount >= 0.0
                {
                    state
                        .subscriptions
                        .insert(subscription.subscription_id.clone(), subscription);
                }
            }
        }
    }
    let rules: Vec<String> = data
        .get("rules")
        .and_then(|v| v.as_array())
        .map(|items| {
            items
                .iter()
                .filter_map(|value| value.as_str().map(str::to_string))
                .filter(|rule_id| RULE_DEFINITIONS.iter().any(|rule| rule.id == rule_id))
                .collect()
        })
        .unwrap_or_default();
    let (created, updated, evaluated, gaps) = state.evaluate(company_id.as_deref(), &rules);
    ctx.add_result(json!({
        "company_id": company_id,
        "rules_evaluated": evaluated,
        "suggestions_created": created,
        "suggestions_updated": updated,
        "data_gaps": gaps,
    }));
}

// ---------------------------------------------------------------------------
// Module
// ---------------------------------------------------------------------------

pub struct AdvisorModule {
    state: Arc<AdvisorState>,
}

impl AdvisorModule {
    pub fn new() -> Self {
        Self {
            state: Arc::new(AdvisorState::new()),
        }
    }
}

impl Default for AdvisorModule {
    fn default() -> Self {
        Self::new()
    }
}

impl Module for AdvisorModule {
    fn id(&self) -> &'static str {
        "advisor"
    }

    fn name(&self) -> &'static str {
        "Advisor"
    }

    fn description(&self) -> &'static str {
        "Rule-based recommendations over company data: cash-flow warnings, overdue-invoice follow-ups, churn signals, expiring licenses, and underused subscriptions. Every suggestion cites its rule, severity formula, and source data; nothing is ever auto-acted on."
    }

    fn requires(&self) -> &[&'static str] {
        &["billing", "licensing", "crm", "notifications", "audit"]
    }

    fn available_as_product(&self) -> bool {
        false
    }

    fn init(&self, ctx: &AppContext) -> UnifiedResult<()> {
        *self
            .state
            .hooks
            .write()
            .expect("hooks lock poisoned") = ctx.hooks.clone();
        Ok(())
    }

    fn register_hooks(&self, bus: &HookBus) {
        for event in ["invoice.created", "invoice.paid", "invoice.voided"] {
            let state = self.state.clone();
            let handler: HookHandler =
                Arc::new(move |ctx: &mut HookContext| on_invoice_event(state.clone(), ctx));
            bus.register(event, "advisor", handler);
        }
        let state = self.state.clone();
        let handler: HookHandler =
            Arc::new(move |ctx: &mut HookContext| on_payment_recorded(state.clone(), ctx));
        bus.register("invoice.payment.recorded", "advisor", handler);
        let state = self.state.clone();
        let handler: HookHandler =
            Arc::new(move |ctx: &mut HookContext| on_license_expiring(state.clone(), ctx));
        bus.register("license.expiring", "advisor", handler);
        let state = self.state.clone();
        let handler: HookHandler =
            Arc::new(move |ctx: &mut HookContext| on_evaluate_requested(state.clone(), ctx));
        bus.register("advisor.evaluate_requested", "advisor", handler);
    }

    fn configure_routes(&self, cfg: &mut web::ServiceConfig) {
        cfg.app_data(web::Data::new(self.state.clone()));
        cfg.service(
            web::scope("/api/v1/advisor")
                // Literal segments first: they must win over `/{id}`.
                .route("/suggestions/re-evaluate", web::post().to(re_evaluate))
                .route("/suggestions", web::get().to(list_suggestions))
                .route("/suggestions/{id}", web::get().to(get_suggestion))
                .route(
                    "/suggestions/{id}/acknowledge",
                    web::post().to(acknowledge_suggestion),
                )
                .route(
                    "/suggestions/{id}/dismiss",
                    web::post().to(dismiss_suggestion),
                )
                .route("/suggestions/{id}/snooze", web::post().to(snooze_suggestion))
                .route("/rules", web::get().to(list_rules))
                .route("/rule-runs", web::get().to(list_rule_runs)),
        );
    }

    fn route_info(&self) -> Vec<RouteInfo> {
        vec![
            RouteInfo { method: "GET", path: "/api/v1/advisor/suggestions", owner: "advisor", description: "List suggestions (paginated; filter by severity, status, company_id, rule_id)." },
            RouteInfo { method: "POST", path: "/api/v1/advisor/suggestions/re-evaluate", owner: "advisor", description: "Evaluate rules on demand for a company (optional CRM activity and subscription snapshots)." },
            RouteInfo { method: "GET", path: "/api/v1/advisor/suggestions/{id}", owner: "advisor", description: "Get one suggestion with its rule, severity formula, and source figures." },
            RouteInfo { method: "POST", path: "/api/v1/advisor/suggestions/{id}/acknowledge", owner: "advisor", description: "Acknowledge a suggestion." },
            RouteInfo { method: "POST", path: "/api/v1/advisor/suggestions/{id}/dismiss", owner: "advisor", description: "Dismiss a suggestion (never resurrected by re-evaluation)." },
            RouteInfo { method: "POST", path: "/api/v1/advisor/suggestions/{id}/snooze", owner: "advisor", description: "Snooze a suggestion until a date or for a number of days." },
            RouteInfo { method: "GET", path: "/api/v1/advisor/rules", owner: "advisor", description: "List the rule definitions with conditions and severity formulas." },
            RouteInfo { method: "GET", path: "/api/v1/advisor/rule-runs", owner: "advisor", description: "List rule evaluation runs (audit trail of what was evaluated)." },
        ]
    }
}

pub fn register(registry: &ModuleRegistry) {
    registry.register(Arc::new(AdvisorModule::new()));
}
