//! app_sync - helpers.

use unified_core::context::AppContext;
use unified_core::error::{UnifiedError, UnifiedResult};
use actix_web::HttpRequest;


/// Caller identity: the server-verified caller, exactly like the
/// other modules. The role is checked through the `role.check` hook
/// and the check fails closed: no answer means not allowed. `actor`
/// is the verified user id; it is recorded as the owner of resources
/// the caller creates (for example a registered device).
pub(crate) struct Caller {
    pub(crate) actor: String,
    pub(crate) role: String,
}


pub(crate) fn caller(req: &HttpRequest) -> UnifiedResult<Caller> {
    let verified = unified_core::caller::require_caller(req)?;
    let actor = verified.user_id.clone();
    let role = verified.role().to_string();
    Ok(Caller { actor, role })
}


pub(crate) fn check_capability(ctx: &AppContext, role: &str, permission: &str) -> bool {
    let context = ctx.hooks.emit(
        "role.check",
        serde_json::json!({ "role": role, "permission": permission, "allowed": false }),
    );
    context
        .get("allowed")
        .and_then(|value| value.as_bool())
        .unwrap_or(false)
}


pub(crate) fn require_permission(
    ctx: &AppContext,
    req: &HttpRequest,
    permission: &str,
) -> UnifiedResult<()> {
    let who = caller(req)?;
    if check_capability(ctx, &who.role, permission) {
        Ok(())
    } else {
        Err(UnifiedError::forbidden(format!(
            "Role \"{}\" does not hold permission \"{}\"",
            who.role, permission
        )))
    }
}

