    #[test]
    fn caller_ignores_role_claims_in_the_query_string() {
        // Regression test for the query-parameter role spoof: a
        // `?viewer_role=admin` query with no verified caller must
        // still fail, and a query role must never override the
        // verified caller.
        let req = TestRequest::default()
            .uri("/api/v1/advisor/suggestions?viewer_id=user-1&viewer_role=admin")
            .to_http_request();
        assert!(caller(&req).is_err());
        let req = {
            let req = TestRequest::default()
            .uri("/api/v1/advisor/suggestions?viewer_role=admin")
            .to_http_request();
            {
                use actix_web::HttpMessage;
                req.extensions_mut().insert(
                    unified_core::auth::Caller::verified(test_user_uuid("user-1"), Vec::new())
                        .with_roles(vec!["viewer".to_string()]),
                );
            }
            req
        };
        let found = caller(&req).unwrap();
        assert_eq!(found.role, "viewer");
    }

    #[test]
    fn major_minor_conversions_round_trip() {
        assert_eq!(major_to_minor(10.25, "USD"), 1025);
        assert_eq!(major_to_minor(10.005, "USD"), 1001);
        assert_eq!(major_to_minor(10.0, "JPY"), 10);
        assert_eq!(minor_to_major(1025, "USD"), 10.25);
        assert_eq!(minor_to_major(1025, "JPY"), 1025.0);
        assert_eq!(minor_to_major(-250, "EUR"), -2.5);
    }
