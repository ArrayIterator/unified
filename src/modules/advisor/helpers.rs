/// True for zero-decimal currencies (no minor units), matching the
/// billing and store modules' list.
pub(crate) fn is_zero_decimal_currency(currency: &str) -> bool {
    unified_core::db::money::is_zero_decimal_currency(currency)
}

/// Convert a major-unit amount from a hook payload to integer minor
/// units. Rounds half away from zero, matching `serde_major`.
pub(crate) fn major_to_minor(amount_major: f64, currency: &str) -> i64 {
    if is_zero_decimal_currency(currency) {
        amount_major.round() as i64
    } else {
        (amount_major * 100.0).round() as i64
    }
}

/// Convert integer minor units to major units, as suggestion
/// figures and human-readable bodies carry them. This is the
/// boundary conversion out of the integer representation.
pub(crate) fn minor_to_major(amount_minor: i64, currency: &str) -> f64 {
    if is_zero_decimal_currency(currency) {
        amount_minor as f64
    } else {
        let major = amount_minor as f64 / 100.0;
        (major * 100.0).round() / 100.0
    }
}

pub(crate) fn new_id() -> String {
    Uuid::new_v4().to_string()
}


pub(crate) fn paginate<T: Serialize + Clone>(items: Vec<T>, params: &PaginationParams) -> PageResult<T> {
    let pagination = params.normalized();
    let total = items.len() as u64;
    let start = ((pagination.page - 1) * pagination.per_page) as usize;
    let page_items: Vec<T> = items
        .into_iter()
        .skip(start)
        .take(pagination.per_page as usize)
        .collect();
    PageResult::new(page_items, total, &pagination)
}


pub(crate) fn matches_search(haystack: &str, params: &PaginationParams) -> bool {
    match &params.search {
        Some(needle) if !needle.trim().is_empty() => haystack
            .to_lowercase()
            .contains(&needle.trim().to_lowercase()),
        _ => true,
    }
}


/// Caller identity: the server-verified caller (user id plus
/// server-resolved role, both required for capability checks),
/// exactly like the exams module. Identity
/// is resolved from request headers only: query parameters are
/// never trusted for authorization, so `?viewer_role=admin` cannot
/// grant `advisor:manage`.
pub(crate) struct Caller {
    pub(crate) actor: String,
    pub(crate) role: String,
}


pub(crate) fn caller(req: &HttpRequest) -> UnifiedResult<Caller> {
    let verified = unified_core::caller::require_caller(req)?;
    let actor = verified.user_id.clone();
    let role = verified.role().to_string();
    Ok(Caller { actor, role })
}


/// Fail when no role was supplied or the role lacks the permission.
pub(crate) fn require_capability(
    state: &AdvisorState,
    role: Option<&str>,
    permission: &str,
) -> UnifiedResult<()> {
    match role {
        Some(role) if state.check_capability(role, permission) => Ok(()),
        _ => Err(UnifiedError::forbidden(format!(
            "Role lacks required capability: {permission}"
        ))),
    }
}

