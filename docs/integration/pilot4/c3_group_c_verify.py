#!/usr/bin/env python3
"""C3 pilot 4 group C verification: hr, marketing, webinars,
meetings, assets, site_builder, panels, seo.

For each module, per routed handler (same routed-set rule as
/tmp/c3_verify.py: names appearing in `.to(name)` in the module):
  - guarded: body contains `require_tenant(&req)` (closure `let _tenant`
    line or direct-style if-let gate block, both first)
  - order: the guard precedes the first identity/capability call
    (`caller(&req)`, `actor_id(&req)`, `caller_roles(&req)`,
    `caller_role(&req)`, `authorize(`, `authorize_view(`,
    `authorize_manage(`, `require_permission(`)
  - scope-checked: body mentions a scope marker; otherwise gate-only
    (all group-C modules are gate-only: their records carry no
company field, so no scope marker is expected; under
    carve-out 3 their writes stay tenant-gate-only until C11 lands)
  - excluded: names passed on the command line after the module

Panels' six `list_*_records` handlers are generated by the
`list_records_handler!` macro: each macro invocation counts as one
handler, and its guard status is read from the macro definition body.

Usage: c3_group_c_verify.py <module> [excluded ...]
Exit code 0 only when missing == 0 and order violations == 0.
"""
import os
import re
import sys

ROOT = "/home/hatch/workspace/unified-push/src/modules"

SCOPE_MARKERS = (
    "in_company_scope",
    "require_record_in_company_scope",
    "require_company_match",
    "caller_company",
    # The strict write gate and the
    # writable record checks count as scope markers too.
    "require_company_for_write",
    "require_record_writable_in_company_scope",
    "require_record_writable_in_company_scope_str",
    "require_record_writable_in_company_scope_uuid",
    "require_note_writable_in_company_scope",
    "require_attempt_writable_in_scope",
    "require_exam_writable_by_id_in_scope",
    "require_risk_writable_in_scope",
)

IDENTITY_CALLS = (
    "caller(&req)",
    "actor_id(&req)",
    "caller_roles(&req)",
    "caller_role(&req)",
    "authorize(",
    "authorize_view(",
    "authorize_manage(",
    "require_permission(",
)


def brace_end(src, i):
    depth = 0
    while i < len(src):
        c = src[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(src)


def check_body(name, body, guard_at_out):
    """Return (guarded, order_ok, scope_checked)."""
    guard_at = body.find("require_tenant(&req)")
    if guard_at == -1:
        return False, True, False
    first_identity = min(
        (body.find(call) for call in IDENTITY_CALLS if body.find(call) != -1),
        default=-1,
    )
    order_ok = first_identity == -1 or first_identity > guard_at
    scope_checked = any(marker in body for marker in SCOPE_MARKERS)
    return True, order_ok, scope_checked


def main():
    mod = sys.argv[1]
    excl = set(sys.argv[2:])
    mdir = os.path.join(ROOT, mod)
    routed = set()
    for f in os.listdir(mdir):
        if not f.endswith(".rs"):
            continue
        src = open(os.path.join(mdir, f), encoding="utf-8", errors="replace").read()
        routed |= set(re.findall(r"\.to\((\w+)\)", src))
    missing, ok, excluded, order_bad = [], [], [], []
    scope_checked, gate_only = [], []
    # Panels macro: guard status comes from the macro definition body.
    macro_body = ""
    macro_handlers = set()
    for f in sorted(os.listdir(mdir)):
        if not f.endswith(".rs"):
            continue
        src = open(os.path.join(mdir, f), encoding="utf-8", errors="replace").read()
        for m in re.finditer(r"macro_rules!\s+(\w+)\s*\{", src):
            j = src.find("{", m.end() - 1)
            macro_body = src[j : brace_end(src, j)]
        macro_handlers |= set(
            re.findall(r"list_records_handler!\((\w+),", src)
        )
    for f in sorted(os.listdir(mdir)):
        if not f.endswith(".rs"):
            continue
        src = open(os.path.join(mdir, f), encoding="utf-8", errors="replace").read()
        test_idx = src.find("#[cfg(test)]")
        head = src if test_idx < 0 else src[:test_idx]
        for m in re.finditer(r"pub\(crate\) async fn (\w+)\s*\(", head):
            name = m.group(1)
            if name not in routed:
                continue
            j = head.find("{", m.end())
            body = head[j : brace_end(head, j)]
            if name in excl:
                excluded.append(f"{f}:{name}")
                continue
            guarded, order_ok, is_scope = check_body(name, body, None)
            if not guarded:
                missing.append(f"{f}:{name}")
                continue
            ok.append(f"{f}:{name}")
            if not order_ok:
                order_bad.append(f"{f}:{name}")
            (scope_checked if is_scope else gate_only).append(f"{f}:{name}")
    for name in sorted(macro_handlers):
        if name not in routed:
            continue
        if name in excl:
            excluded.append(f"macro:{name}")
            continue
        guarded, order_ok, is_scope = check_body(name, macro_body, None)
        if not guarded:
            missing.append(f"macro:{name}")
            continue
        ok.append(f"macro:{name}")
        if not order_ok:
            order_bad.append(f"macro:{name}")
        (scope_checked if is_scope else gate_only).append(f"macro:{name}")
    print(
        f"{mod}: guarded={len(ok)} (scope-checked={len(scope_checked)}, "
        f"gate-only={len(gate_only)}) missing={len(missing)} "
        f"excluded={len(excluded)} order_violations={len(order_bad)}"
    )
    for x in missing:
        print("  MISSING:", x)
    for x in order_bad:
        print("  ORDER:", x)
    for x in excluded:
        print("  EXCL:", x)
    if scope_checked:
        print("  SCOPE-CHECKED (unexpected for gate-only modules):")
        for x in scope_checked:
            print("   ", x)
    return 1 if missing or order_bad else 0


if __name__ == "__main__":
    sys.exit(main())
